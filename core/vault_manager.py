"""
core/vault_manager.py
──────────────────────
Reads and writes Obsidian-compatible Markdown files with YAML front-matter.

Design principle:
  All data is plain .md files. The user can open the vault in Obsidian,
  iA Writer, or any text editor at any time. NoPlanB never locks data into
  a proprietary format.

Front-matter schema for daily task logs:
  ---
  task_id:      <str>   unique identifier (uuid4)
  date:         <str>   ISO 8601 date
  atomic_task:  <str>   the exact micro-task presented to the user
  duration_min: <int>   planned duration in minutes
  obstacle:     <str>   the anticipated internal/external blocker
  intention:    <str>   the If-Then implementation intention
  status:       <str>   pending | done | stuck | resist | deferred
  mood:         <int>   1-5 self-rating (captured on completion)
  started_at:   <str>   ISO 8601 datetime (when user first saw the task)
  completed_at: <str>   ISO 8601 datetime (when DONE signal received)
  friction_sec: <int>   elapsed seconds until first DONE/STUCK/RESIST signal
  ---
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Optional

import frontmatter

from core.config import settings


# ─────────────────────────── helpers ─────────────────────────────────────────

def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


def _task_path(task_id: str) -> Path:
    """Return the Path of the daily log file for a given task_id."""
    today = datetime.now(timezone.utc).date().isoformat()
    return settings.daily_dir / f"{today}_{task_id[:8]}.md"


# ─────────────────────────── public API ──────────────────────────────────────

def create_task_entry(
    *,
    atomic_task: str,
    duration_min: int,
    obstacle: str,
    intention: str,
    woop_transcript: str = "",
) -> str:
    """
    Create a new daily task log in the vault.
    Returns the task_id.
    """
    settings.ensure_vault_dirs()

    task_id = str(uuid.uuid4())
    metadata = {
        "task_id":      task_id,
        "date":         datetime.now(timezone.utc).date().isoformat(),
        "atomic_task":  atomic_task,
        "duration_min": duration_min,
        "obstacle":     obstacle,
        "intention":    intention,
        "status":       "pending",
        "mood":         None,
        "started_at":   _now_iso(),
        "completed_at": None,
        "friction_sec": None,
    }

    body = f"""## Task

**{atomic_task}**

### WOOP Breakdown

| Field | Value |
|-------|-------|
| Anticipated Obstacle | {obstacle} |
| If-Then Plan | {intention} |
| Planned Duration | {duration_min} min |

### WOOP Interrogation Transcript

{woop_transcript if woop_transcript else "_Transcript not recorded._"}

---
*Generated by NoPlanB – data never leaves this device.*
"""

    post = frontmatter.Post(body, **metadata)
    path = _task_path(task_id)
    path.write_text(frontmatter.dumps(post), encoding="utf-8")
    return task_id


def update_task_status(
    task_id: str,
    status: str,  # done | stuck | resist | deferred
    mood: Optional[int] = None,
    friction_sec: Optional[int] = None,
) -> None:
    """
    Update the status, mood, and timing fields of an existing task log.
    """
    path = _find_task_path(task_id)
    if path is None:
        raise FileNotFoundError(f"Task log for {task_id} not found in vault.")

    post = frontmatter.load(str(path))
    post["status"] = status
    if status == "done":
        post["completed_at"] = _now_iso()
    if mood is not None:
        post["mood"] = mood
    if friction_sec is not None:
        post["friction_sec"] = friction_sec

    path.write_text(frontmatter.dumps(post), encoding="utf-8")


def get_task(task_id: str) -> Optional[dict]:
    """Load and return the front-matter metadata for a task."""
    path = _find_task_path(task_id)
    if path is None:
        return None
    post = frontmatter.load(str(path))
    return dict(post.metadata)


def list_recent_tasks(n: int = 20) -> list[dict]:
    """
    Return the front-matter of the N most-recent daily task files,
    sorted newest-first. Used for context retrieval.
    """
    settings.ensure_vault_dirs()
    files = sorted(settings.daily_dir.glob("*.md"), reverse=True)[:n]
    results = []
    for f in files:
        post = frontmatter.load(str(f))
        results.append(dict(post.metadata))
    return results


def save_crucible_transcript(task_id: str, transcript: str) -> None:
    """
    Save the full Socratic WOOP interrogation transcript to vault/crucibles/.
    Keeps raw AI conversation separate from the clean daily log.
    """
    settings.ensure_vault_dirs()
    path = settings.crucibles_dir / f"{task_id}.md"
    content = f"""# WOOP Interrogation – {task_id}

> Generated by NoPlanB Socratic Interrogator (Gemma – local, air-gapped).
> This transcript never leaves your device.

---

{transcript}
"""
    path.write_text(content, encoding="utf-8")


def save_horizon(title: str, content: str, horizon_type: str = "yearly") -> Path:
    """
    Save a long-horizon goal document (yearly/monthly) to vault/horizons/.
    horizon_type: 'yearly' | 'monthly'
    """
    settings.ensure_vault_dirs()
    date_str = datetime.now(timezone.utc).date().isoformat()
    filename = f"{horizon_type}_{date_str}_{title[:30].replace(' ', '_')}.md"
    path = settings.horizons_dir / filename
    path.write_text(content, encoding="utf-8")
    return path


# ─────────────────────────── internal ────────────────────────────────────────

def _find_task_path(task_id: str) -> Optional[Path]:
    """Search daily/ for a file containing the given task_id prefix."""
    settings.ensure_vault_dirs()
    prefix = task_id[:8]
    matches = list(settings.daily_dir.glob(f"*{prefix}*.md"))
    return matches[0] if matches else None
